-- Send & Sign, PR 1 of 6. APPLIED to the live FORA Supabase project
-- (wzyvbtzxxdcxgvbkcqmt) via mcp__Supabase__apply_migration, migration name
-- "sent_documents_schema", 2026-10-21. Verified after applying: RLS on, no
-- policies, bucket private with the PDF-only and 20 MB limits.
--
-- A supervisor uploads a PDF, sends it to one or more roster members, and
-- each recipient either signs it (mode 'sign') or taps "Got it" (mode
-- 'read'). The returned copy is the original plus one signature page, filed
-- by category.
--
-- One row = one document sent to ONE person. Sending to five people writes
-- five rows that share a batch_id, so each person has their own status,
-- due date and signed copy, and a recipient never sees who else got it.
--
--   roster_id         the recipient. Per-company only, same as
--                     worker_certifications: rows follow the roster row
--                     and are kept when someone is deactivated (a
--                     company's training records outlive the job), and only
--                     an explicit roster delete cascades them away.
--   sent_by_roster_id the sender. Null for a founder (admin) session, which
--                     has no roster row. sent_by_name is stamped at send
--                     time so the tracker still reads right after a rename.
--   category          fixed list for v1. Extending it later means editing
--                     the check, same as any enum-like text column here.
--   mode              'sign' (drawn signature) | 'read' (acknowledge only).
--   status            sent -> opened -> completed, or cancelled by the
--                     sender. "Overdue" is derived at read time from due_at,
--                     never stored (same reasoning as document_assignments).
--   original_path     the uploaded PDF in the sent-documents bucket.
--   signed_path       the original plus signature page, set on completion.
--   original_sha256 / signed_sha256
--                     hex digests, so a filed copy can be shown unaltered.
--
-- Storage paths are namespaced <company_id>/<roster_id>/<category>/... by
-- the API (server-lib/uploadUrls.js adds the unguessable segment). The
-- bucket is shared across companies, which is the known open item in
-- TODO.md, so the namespace prefix is checked server side on every read.

create table if not exists public.sent_documents (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  roster_id bigint not null references public.roster(id) on delete cascade,
  batch_id uuid not null default gen_random_uuid(),
  sent_by_roster_id bigint references public.roster(id) on delete set null,
  sent_by_name text not null default '',
  title text not null,
  category text not null default 'notices'
    check (category in ('training', 'onboarding', 'notices', 'policies', 'other')),
  mode text not null default 'sign'
    check (mode in ('sign', 'read')),
  note text,
  due_at timestamptz,
  status text not null default 'sent'
    check (status in ('sent', 'opened', 'completed', 'cancelled')),
  original_path text not null,
  original_sha256 text,
  signed_path text,
  signed_sha256 text,
  opened_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now()
);

-- Every read is company scoped; the worker inbox and the profile drawer
-- filter by recipient on top of that.
create index if not exists sent_documents_company_id_idx
  on public.sent_documents (company_id, created_at desc);
create index if not exists sent_documents_roster_id_idx
  on public.sent_documents (roster_id, status);
create index if not exists sent_documents_batch_id_idx
  on public.sent_documents (batch_id);

-- RLS: deny-by-default backstop with no policies, matching every other
-- table (README, Architecture). The api/*.js service-role key is the real
-- access boundary.
alter table public.sent_documents enable row level security;

-- Storage: private bucket, PDF only, 20 MB, matching the limits already
-- applied to worker-certifications (docs/schema/worker-bucket-limits-
-- migration.sql). Created with the limits in place so there is never a
-- window where it accepts any file type. No storage.objects policies are
-- added: every upload goes through a signed upload token, and every read
-- through a signed URL, both issued by the API.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('sent-documents', 'sent-documents', false, 20971520, array['application/pdf'])
on conflict (id) do nothing;
